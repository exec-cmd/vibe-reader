#!/usr/bin/env python3
"""Download the third-party files embedded in the UI: fonts, KaTeX, highlight.js, pdf.js.

Run from the repository root:  python3 scripts/vendor.py
Versions are pinned below; the files are committed, so this only runs on upgrades.
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

UI = Path(__file__).resolve().parent.parent / "src" / "gui" / "ui"
CHROME = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"

KATEX = "https://cdn.jsdelivr.net/npm/katex@0.16.22/dist"
HLJS = "https://cdnjs.cloudflare.com/ajax/libs/highlight.js/11.11.1"
PDFJS = "https://cdn.jsdelivr.net/npm/pdfjs-dist@4.10.38"

# family -> (Google Fonts axis spec, folder in google/fonts for the license)
FONTS = {
    "Literata": ("ital,opsz,wght@0,7..72,400..700;1,7..72,400..700", "literata"),
    "Spectral": ("ital,wght@0,400;0,600;1,400;1,600", "spectral"),
    "Cormorant Garamond": ("ital,wght@0,400..700;1,400..700", "cormorantgaramond"),
    "Playfair Display": ("ital,wght@0,400..900;1,400..900", "playfairdisplay"),
    "Onest": ("wght@400..700", "onest"),
    "JetBrains Mono": ("ital,wght@0,400..700;1,400..700", "jetbrainsmono"),
}
SUBSETS = {"cyrillic", "cyrillic-ext", "latin", "latin-ext"}


def get(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": CHROME})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def save(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    print(f"{len(data) // 1024:>6} KB  {path.relative_to(UI)}")


def fonts() -> None:
    out = UI / "fonts"
    css_out = ["/* Generated by scripts/vendor.py from Google Fonts. All fonts: SIL Open Font License 1.1. */\n"]
    for family, (axes, folder) in FONTS.items():
        css = get(f"https://fonts.googleapis.com/css2?family={family.replace(' ', '+')}:{axes}&display=swap").decode()
        slug = folder
        for subset, block in re.findall(r"/\* ([\w-]+) \*/\s*(@font-face \{.*?\})", css, re.S):
            if subset not in SUBSETS:
                continue
            style = re.search(r"font-style: (\w+)", block).group(1)
            weight = re.search(r"font-weight: ([\d ]+);", block).group(1).replace(" ", "-")
            url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
            name = f"{slug}-{style}-{weight}-{subset}.woff2"
            save(out / name, get(url))
            css_out.append(block.replace(url, name) + "\n")
        save(out / f"{slug}-OFL.txt", get(f"https://raw.githubusercontent.com/google/fonts/main/ofl/{folder}/OFL.txt"))
    save(out / "fonts.css", "".join(css_out).encode())


def katex() -> None:
    out = UI / "vendor" / "katex"
    css = get(f"{KATEX}/katex.min.css")
    save(out / "katex.min.css", css)
    save(out / "katex.min.js", get(f"{KATEX}/katex.min.js"))
    for font in sorted(set(re.findall(rb"fonts/([\w-]+\.woff2)", css))):
        save(out / "fonts" / font.decode(), get(f"{KATEX}/fonts/{font.decode()}"))
    save(out / "LICENSE", get("https://cdn.jsdelivr.net/npm/katex@0.16.22/LICENSE"))


def highlight() -> None:
    out = UI / "vendor" / "highlight"
    save(out / "highlight.min.js", get(f"{HLJS}/highlight.min.js"))
    save(out / "LICENSE", get("https://raw.githubusercontent.com/highlightjs/highlight.js/11.11.1/LICENSE"))


def pdfjs() -> None:
    out = UI / "vendor" / "pdfjs"
    save(out / "pdf.min.mjs", get(f"{PDFJS}/build/pdf.min.mjs"))
    save(out / "pdf.worker.min.mjs", get(f"{PDFJS}/build/pdf.worker.min.mjs"))
    save(out / "LICENSE", get(f"{PDFJS}/LICENSE"))


if __name__ == "__main__":
    parts = {"fonts": fonts, "katex": katex, "highlight": highlight, "pdfjs": pdfjs}
    for name in sys.argv[1:] or parts:
        parts[name]()
